#!/usr/bin/env python3
"""benchmarks/ACCURACY_SUMMARY.md, generated from three stored artefacts so it
cannot drift from them:

    accuracy_summary.py            # write the page
    accuracy_summary.py --check    # exit 1 if the page differs from what the artefacts give

Sources (nothing is run): ``benchmarks/exact_scoreboard.json`` (the floor-free
``exact`` measure against the 50-digit truth), ``benchmarks/NEXT_DEFAULTS_REHEARSAL.md``
(strict reference counts today and under the release profile) and
``benchmarks/IDEAL_SWITCH_FLIP_EVIDENCE.md`` (strict counts per switch variant); ``benchmarks/EXACT_TRUTH.md`` for the circuits the
truth engine refuses by name.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCOREBOARD = ROOT / "exact_scoreboard.json"
REHEARSAL = ROOT / "NEXT_DEFAULTS_REHEARSAL.md"
FLIP = ROOT / "IDEAL_SWITCH_FLIP_EVIDENCE.md"
TRUTH = ROOT / "EXACT_TRUTH.md"          # which circuits the truth engine refuses, and why
OUT = ROOT / "ACCURACY_SUMMARY.md"
THRESHOLDS = (1e-3, 1e-6, 1e-9)
STRICT = ("pwl", "pwl+restart", "pwl+split", "trbdf2", "dsed", "trbdf2+esdirk43",
          "pwl+next", "trbdf2+next", "dsed+next", "auto", "auto+next")
SAME = ("pwl+split", "trbdf2", "dsed")   # the same circuit on these, beside each large error


def _md_table(text: str, heading: str) -> list:
    """Rows (lists of cells) of the first table after ``heading``."""
    body = text.split(heading, 1)[1]
    rows, started = [], False
    for ln in body.splitlines():
        if ln.startswith("|"):
            started = True
            if not ln.startswith("|---"):
                rows.append([c.strip() for c in ln.strip().strip("|").split("|")])
        elif started:
            break
    return rows


def _g(x: float) -> str:
    return f"{x:.2g}"


def build() -> str:
    sb = json.loads(SCOREBOARD.read_text(encoding="utf-8"))
    reh = REHEARSAL.read_text(encoding="utf-8")
    flip = FLIP.read_text(encoding="utf-8")
    recs = sorted(sb["circuits"], key=lambda r: r["circuit"])
    cfgs = list(sb["configs"])
    n = len(recs)
    L = ["# Accuracy summary", "",
         "Generated by `benchmarks/tools/accuracy_summary.py` from `benchmarks/exact_scoreboard.json`, "
         "`benchmarks/NEXT_DEFAULTS_REHEARSAL.md`, `benchmarks/IDEAL_SWITCH_FLIP_EVIDENCE.md` and "
         "`benchmarks/EXACT_TRUTH.md` (do not edit; `--check` fails when this page differs from them). "
         f"Scoreboard rendered on `{sb.get('commit', 'commit not recorded')}` (the tree its runs used: "
         "`benchmarks/EXACT_SCOREBOARD.md`, `## Notes`).", ""]

    L += ["## Circuits within a distance of the 50-digit truth", "",
          f"`exact` measure (`benchmarks/tools/metrics.py`, time-weighted RMS over the engine's own samples, "
          f"fraction of the truth's span) on the {n} circuits the truth solves "
          "(`benchmarks/EXACT_SCOREBOARD.md`). `not graded` = the run refused or failed.", "",
          "| configuration | engine | keywords | form | < 1e-3 | < 1e-6 | < 1e-9 | not graded |",
          "|---|---|---|---|---:|---:|---:|---:|"]
    for k in cfgs:
        d = sb["configs"][k]
        ex = [r["cells"][k]["exact"] for r in recs if "exact" in r["cells"].get(k, {})]
        ng = sum(1 for r in recs if k in r["cells"] and "exact" not in r["cells"][k])
        kw = ", ".join(f"{a}={d['kwargs'][a]!r}" for a in sorted(d["kwargs"])) or "-"
        L.append(f"| {k} | {d['engine']} | {kw} | {d['form'] or '-'} | "
                 + " | ".join(str(sum(e < t for e in ex)) for t in THRESHOLDS) + f" | {ng} |")

    rows = {r[0]: r for r in _md_table(reh, "## Counts, differential matrix")}
    head = _md_table(reh, "## Counts, differential matrix")[0]
    ncirc = next(ln for ln in reh.split("## Counts, differential matrix", 1)[1].splitlines()
                 if ln.endswith("circuits.")).rstrip(".")
    L += ["", "## Strict reference counts", "",
          f"From `benchmarks/NEXT_DEFAULTS_REHEARSAL.md` ({ncirc}; the strict gate against the harness "
          "reference, not against the truth). `+next` = the release profile on that engine; `auto+next` = "
          "the release route.", "",
          "| configuration | " + " | ".join(head[2:8]) + " |", "|---|" + "---:|" * 6]
    for k in STRICT:
        if k in rows:
            L.append(f"| {k} | " + " | ".join(rows[k][2:8]) + " |")
    if "auto" in rows and "auto+next" in rows:
        L += ["", f"`auto+next` agrees on {rows['auto+next'][2]} circuits against {rows['auto'][2]} for `auto` today: "
              "the release route runs a script without dt on the exact engine ("
              + ("on the profile's `output_rtol` output grid" if "| dsed | `output_rtol` |" in reh
                 else "at its default output ceiling") + ") where "
              "every segment is exact, else on trbdf2; "
              "the cells and the blocker list are in `NEXT_DEFAULTS_REHEARSAL.md`."]

    frows = _md_table(flip, "## Summary")
    fh = frows[0]
    L += ["", "## Strict counts per switch variant", "",
          "From `benchmarks/IDEAL_SWITCH_FLIP_EVIDENCE.md` (`branch` = branch form with the netlist's values; "
          "`ideal` = R_on = 0, V_f = 0, graded against its own converged reference). A row that does not add "
          "up to the circuit count holds `not comparable` (ideal twin whose reference uncertainty is above "
          "tol/10) or `n/a` cells: the source lists them.", "",
          "| configuration | variant | " + " | ".join(fh[2:6]) + " |", "|---|---|" + "---:|" * 4]
    for r in frows[1:]:
        if r[1] in ("default", "branch", "ideal"):
            L.append(f"| {r[0]} | {r[1]} | " + " | ".join(r[2:6]) + " |")

    L += ["", "## Five largest remaining errors per configuration", "",
          "`departs at` = the last truth event before the first sample off by more than the cell's "
          "tolerance (the scoreboard's `departure`; `-` = no sample beyond the tolerance); it locates the "
          "error, it is not its cause. The last columns are the same circuit on other configurations. This "
          "page states no cause; see `benchmarks/EXACT_SCOREBOARD.md` (`## Notes`, `## Findings for the "
          "engine tracks`), `benchmarks/EXACT_TRUTH.md` and `benchmarks/circuits/NOTES_known_issues.md`.", "",
          "| configuration | circuit | exact | departs at (truth event) | " + " | ".join(SAME) + " |",
          "|---|---|---:|---|" + "---:|" * len(SAME)]
    for k in cfgs:
        xs = sorted(((r["cells"][k]["exact"], r["circuit"], r["cells"][k]) for r in recs
                     if "exact" in r["cells"].get(k, {})), key=lambda x: (-x[0], x[1]))[:5]
        for e, circ, c in xs:
            ev = (c.get("departure") or {}).get("event")
            where = f"{_g(ev['t'])} s {ev['cause']}" if ev else "-"
            r = next(x for x in recs if x["circuit"] == circ)
            other = [_g(r["cells"][o]["exact"]) if "exact" in r["cells"].get(o, {}) else
                     r["cells"].get(o, {}).get("outcome", "-") for o in SAME]
            L.append(f"| {k} | {circ.removeprefix('circuits/')} | {_g(e)} | {where} | " + " | ".join(other) + " |")

    every = [r[0] for r in _md_table(reh, "## Every cell") if not r[0].startswith("analytic:")][1:]
    solved = {r["circuit"].removeprefix("circuits/") for r in recs}
    no_truth = sorted(c for c in every if c not in solved)
    refused = {r[0].removeprefix("circuits/"): r[1] for r in
               _md_table(TRUTH.read_text(encoding="utf-8"), "## Coverage of the harness's 'runs' circuits")[1:]}
    ref = [c for c in no_truth if c in refused]
    rest = [c for c in no_truth if c not in refused]
    L += ["", "## What the numbers do not cover", "",
          f"- Circuits without a truth: {len(no_truth)} of the {len(every)} reference circuits; they are "
          f"graded by the strict gate only. {len(ref)} are refused by name by the truth engine "
          "(`benchmarks/EXACT_TRUTH.md`, coverage table): " + "; ".join(f"{Path(c).stem} ({refused[c]})" for c in ref)
          + f". {len(rest)} are in its scope but have no truth record in `benchmarks/truth/` (not computed; no "
          "reason recorded): " + ", ".join(Path(c).stem for c in rest) + ".",
          "- Only the engine's samples are graded: what a trace does between its samples is not measured.",
          "- Platform: every number here was measured on macOS (arm64, CPython 3.13); Linux and Windows "
          "are covered by CI tests, not by these artefacts.",
          "- The release profile is not the default: `+next` columns apply it through the harness "
          "(`benchmarks/tools/next_defaults.py`); a plain `simulate()` call does not get it. Its branch form "
          "reaches `add_switch` / `add_diode` called with the netlist's values only (not MOSFET / IGBT "
          "helpers, Shockley diodes or calls with extra arguments).",
          "- The analytic set (closed forms) is in `NEXT_DEFAULTS_REHEARSAL.md`, not in the tables above."]
    return "\n".join(L) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if the page is stale")
    a = ap.parse_args(argv)
    text = build()
    if a.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT.name} is stale: run benchmarks/tools/accuracy_summary.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

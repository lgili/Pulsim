#!/usr/bin/env python3
"""Evidence for trbdf2's opaque-gate step cap (DECISIONS #30 of
add-branch-form-ideal-switch: the cap is kCapPulses = 64 narrowest recent
pulses, the gate sampled every w/2).

cl_boost_pi's loop (5 V -> 10 V boost, PI from duty 0, 100 kHz) over 0.3 ms,
its gate given two ways: declared (the loop's own switch_fn, edges known)
and opaque (a lambda, edges learned). Reports accepted steps per period,
solves, the switch edges seen, and a rounding fuzz of the opaque run
(R and L scaled by 1 + 1e-15 u). Written to
benchmarks/TRBDF2_STEP_CAP_EVIDENCE.md:

    PYTHONPATH=python python3 benchmarks/tools/trbdf2_step_cap_evidence.py [--fuzz N]

The cap itself is a compile-time constant; the numbers before it (cap 2 w)
are DECISIONS #30's.
"""

from __future__ import annotations

import argparse
import statistics
import warnings
from pathlib import Path

import numpy as np

import pulsim as p

OUT = Path(__file__).resolve().parents[1] / "TRBDF2_STEP_CAP_EVIDENCE.md"
T_END, PERIOD = 3e-4, 1e-5


def run(opaque: bool, scale: float = 1.0):
    b = p.CircuitBuilder()
    b.add_voltage_source("Vin", "vin", "gnd", 5.0)
    b.add_resistor("R_dcr", "vin", "n_l", 0.1 * scale)
    b.add_inductor("L1", "n_l", "sw", 47e-6 * scale)
    b.add_switch("SL", "sw", "gnd", 100.0, 1e-6)
    b.add_diode("D", "sw", "out", 100.0, 1e-6)
    b.add_capacitor("C", "out", "gnd", 470e-6, 10.0)
    b.add_resistor("R", "out", "gnd", 40.0)
    pi = p.PIController(Kp=0.005, Ki=50.0, output_min=0.0, output_max=0.9)
    loop = p.bind_pi_to_switch(b, pi=pi, measured="out", setpoint=10.0,
                               switch="SL", freq=1 / PERIOD)
    gate = loop.switch_fn
    with warnings.catch_warnings():   # the 0.28 ns start-up pulse
        warnings.simplefilter("ignore")
        r = p.simulate(b, T_END, engine="trbdf2",
                       switch_fn=(lambda t: gate(t)) if opaque else gate,
                       step_observer=loop.step_observer)
    t = np.asarray(r.times)
    s = np.asarray(r.switch_states)[:, b.switch_index_of("SL")]
    rises = int(np.sum(s[1:] & ~s[:-1]))
    falls = int(np.sum(~s[1:] & s[:-1]))
    per = np.bincount(np.minimum((t[1:] / PERIOD).astype(int),
                                 int(T_END / PERIOD) - 1),
                      minlength=int(T_END / PERIOD))
    st = r._trbdf2_stats
    return dict(accept=st["n_accept"], solves=st["n_solves"], per=per,
                rises=rises, falls=falls, v_end=float(r.v("out")[-1]))


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--fuzz", type=int, default=20)
    a = ap.parse_args()
    op, de = run(True), run(False)
    rng = np.random.default_rng(1)
    fz = [run(True, 1.0 + 1e-15 * rng.uniform(-1, 1)) for _ in range(a.fuzz)]
    acc = [f["accept"] for f in fz]
    ve = [f["v_end"] for f in fz]
    rows = [
        "| gate | accepted | solves | first 0.1 ms | periods 1-2 | rises / falls | v(out) at 0.3 ms |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    for name, x in (("opaque (learned)", op), ("declared", de)):
        rows.append(f"| {name} | {x['accept']:,} | {x['solves']:,} | "
                    f"{int(x['per'][:10].sum()):,} | {int(x['per'][1:3].sum()):,} | "
                    f"{x['rises']} / {x['falls']} | {x['v_end']:.9f} |")
    per = ", ".join(f"{int(n)}" for n in op["per"][:12])
    tail = statistics.median(int(n) for n in op["per"][-10:])
    text = f"""# TR-BDF2 opaque-gate step cap: evidence

Generated by `benchmarks/tools/trbdf2_step_cap_evidence.py`; do not edit.
DECISIONS #30 of add-branch-form-ideal-switch: the step cap of an opaque
`switch_fn` is 64 x the narrowest recent pulse (kCapPulses), the gate sampled
every w/2 inside a step. Before (cap 2 w): 28,049 accepted in 0.3 ms, 26,944
in the first 0.1 ms, 26,490 in periods 1-2; after it, 2,357 / 1,295 / 866
and 5,296 solves (DECISIONS #30; steps binned here by end time, and the
solve count has moved by a few since).

Circuit: cl_boost_pi's loop (5 V -> 10 V boost, PI from duty 0, 100 kHz),
0.3 ms, trbdf2 defaults.

{chr(10).join(rows)}

Opaque, accepted steps per period (first 12): {per}; median of the last 10
periods: {tail}.

Rounding fuzz, opaque gate ({a.fuzz} runs, R_dcr and L1 x (1 + 1e-15 u)):
accepted {min(acc):,} .. {max(acc):,}; v(out) spread {max(ve) - min(ve):.2e} V.
"""
    OUT.write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()

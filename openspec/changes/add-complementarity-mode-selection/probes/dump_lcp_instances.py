"""Dump the LCPs the prototype poses on the five families (task 1.1 / 2.2 fixtures).

Run from the worktree root:
    python3 openspec/changes/add-complementarity-mode-selection/probes/dump_lcp_instances.py

Writes python/tests/oracles/lcp_instances.json (the Python oracle tests) and
core/tests/modes/lcp_instances.inc (the Catch2 tests of the C++ selector). Every LCP is the one
the prototype's selector posed (scaled hybrid coordinates, ideal elements), with Lemke's pivots and
solution. Duplicates are dropped; trivial LCPs (q >= 0, zero pivots) are capped at 5 per family, and every family at 40.
"""
import json
import os
import sys

import numpy as np

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), *[".."] * 4))
sys.path.insert(0, os.path.join(ROOT, "python", "tests", "oracles"))
import lcp_reference as L  # noqa: E402

T = 1e-5


def buck(L_=100e-6):
    c = L.Circuit()
    c.add_Vdc("Vin", "vin", "0", 24.0); c.add_S("S", "vin", "sw"); c.add_D("D1", "0", "sw")
    c.add_L("L", "sw", "vout", L_); c.add_C("C", "vout", "0", 47e-6); c.add_R("vout", "0", 50.0)
    return c


def boost(R):
    c = L.Circuit()
    c.add_Vdc("Vin", "vin", "0", 12.0); c.add_L("L", "vin", "sw", 100e-6)
    c.add_S("S", "sw", "0"); c.add_D("D1", "sw", "out")
    c.add_C("C", "out", "0", 47e-6); c.add_R("out", "0", R)
    return c


def bridge1(Vf):
    c = L.Circuit()
    c.add_Vsin("Vs", "a", "0", 100.0, 50.0)
    c.add_D("D1", "a", "p", V_f=Vf); c.add_D("D3", "0", "p", V_f=Vf)
    c.add_D("D2", "n", "a", V_f=Vf); c.add_D("D4", "n", "0", V_f=Vf)
    c.add_C("C", "p", "n", 1e-3); c.add_R("p", "n", 100.0)
    return c


def bridge3(Ls=None, Id=None, C=None, R=None, Vf=0.0):
    c = L.Circuit()
    for ph, ang in (("a", 0.0), ("b", -2 * np.pi / 3), ("c", 2 * np.pi / 3)):
        src = "s" + ph if Ls else ph
        c.add_Vsin("V" + ph, src, "0", 100.0, 50.0, phase=ang)
        c.add_D("Dt" + ph, ph, "p", V_f=Vf); c.add_D("Db" + ph, "n", ph, V_f=Vf)
    if Ls:
        i0 = {"a": 0.0, "b": -Id, "c": Id}
        for ph in "abc":
            c.add_L("L" + ph, "s" + ph, ph, Ls, i0=i0[ph])
    if Id:
        c.add_Idc("Id", "p", "n", Id)
    if C:
        c.add_C("C", "p", "n", C); c.add_R("p", "n", R)
    return c


RUNS = [
    ("buck_rest", lambda: L.simulate(buck(), 2e-6 + 10 * T, gate=L.pwm(T, 0.3, t0=2e-6),
                                     edges=L.pwm_edges(T, 0.3, 2e-6 + 10 * T, t0=2e-6), h_e=1e-6 * T)),
    ("dcm_buck", lambda: L.simulate(buck(), 40 * T, gate=L.pwm(T, 0.3), edges=L.pwm_edges(T, 0.3, 40 * T),
                                    h_e=1e-6 * T)),
    ("boost_50", lambda: L.simulate(boost(50.0), 40 * T, gate=L.pwm(T, 0.5), edges=L.pwm_edges(T, 0.5, 40 * T),
                                    h_e=1e-6 * T)),
    ("boost_500", lambda: L.simulate(boost(500.0), 40 * T, gate=L.pwm(T, 0.5),
                                     edges=L.pwm_edges(T, 0.5, 40 * T), h_e=1e-6 * T)),
    ("bridge1_vf07", lambda: L.simulate(bridge1(0.7), 0.2, h_e=1e-9)),
    ("bridge1_vf0", lambda: L.simulate(bridge1(0.0), 0.2, h_e=1e-9)),
    ("bridge3_overlap", lambda: L.simulate(bridge3(Ls=1e-3, Id=10.0), 0.06, h_e=1e-9)),
    ("bridge3_cfilter", lambda: L.simulate(bridge3(C=1e-3, R=20.0, Vf=0.7), 0.1, h_e=1e-9)),
]


def main():
    out = []
    for fam, run in RUNS:
        L.LCP_LOG = []
        run()
        log, L.LCP_LOG = L.LCP_LOG, None
        seen, trivial = set(), 0
        for M, q, piv, status in log:
            key = (np.round(M, 9).tobytes(), np.round(q, 9).tobytes())
            if key in seen:
                continue
            seen.add(key)
            if piv == 0:
                trivial += 1
                if trivial > 5:
                    continue
            if sum(o["family"] == fam for o in out) >= 40:
                break
            z, w, piv2, st2 = L.lemke(M, q)
            assert (piv2, st2) == (piv, status)
            enum = L.enumerate_lcp(M, q)
            out.append(dict(family=fam, k=len(q), M=M.tolist(), q=q.tolist(), pivots=piv,
                            status=status, z=z.tolist(), w=w.tolist(), n_enum=len(enum)))
        print(f"{fam}: {len(log)} LCPs posed, {sum(o['family'] == fam for o in out)} kept")
    with open(os.path.join(ROOT, "python/tests/oracles/lcp_instances.json"), "w") as f:
        json.dump(out, f, indent=0)
    os.makedirs(os.path.join(ROOT, "core/tests/modes"), exist_ok=True)
    with open(os.path.join(ROOT, "core/tests/modes/lcp_instances.inc"), "w") as f:
        f.write("// Generated by openspec/changes/add-complementarity-mode-selection/probes/"
                "dump_lcp_instances.py -- do not edit.\n")
        f.write("// {family, k, M (row-major), q, prototype pivots, prototype z, prototype w}\n")
        for o in out:
            r = lambda v: "{" + ", ".join(repr(float(x)) for x in v) + "}"
            f.write(f'{{"{o["family"]}", {o["k"]}, {r(np.ravel(o["M"]))}, {r(o["q"])}, {o["pivots"]}, '
                    f'{r(o["z"])}, {r(o["w"])}}},\n')
    print(f"total {len(out)} instances")


if __name__ == "__main__":
    main()

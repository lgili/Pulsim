#!/usr/bin/env python3
"""Generate benchmarks/RELEASE_GOLDEN_DIFF.md: every fixed-engine golden the
release changed, its old and new value, and the truth that says which is closer.

    golden_diff.py            # needs benchmarks/goldens/pwl (new) and pwl_legacy (old)

Per changed golden (``goldens.compare(old, new)`` not empty): the checkpoint
entry that moved most (old -> new value), then the whole run graded against
its truth under the legacy profile (old) and the defaults (new):
analytic cases against their closed form (``metrics.err_rms``, as the
reference harness); v1 circuits the exact truth solves against the mpmath
truth (``exact_scoreboard.grade``, the ``exact`` measure); the rest (Newton
devices) against trbdf2 at rtol 1e-10 (not independent; said so). A golden
whose new run is FARTHER from its truth is flagged and keeps its old golden.
"""

from __future__ import annotations

import json
import sys
import warnings
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[4]
sys.path[:0] = [str(ROOT / "benchmarks" / "tools"), str(ROOT / "benchmarks")]
import differential_runner as dr  # noqa: E402
import exact_scoreboard as sb  # noqa: E402
import exact_truth as et  # noqa: E402
import goldens  # noqa: E402
import metrics  # noqa: E402
import next_defaults as nd  # noqa: E402
import v1_reader  # noqa: E402
from analytic import BY_ID  # noqa: E402

OUT = ROOT / "benchmarks" / "RELEASE_GOLDEN_DIFF.md"


def moved(old, new):
    """(t, name, old value, new value, rel) of the checkpoint entry that moved most; else n_steps."""
    best = (float("nan"), "n_steps", old["n_steps"], new["n_steps"], 0.0)
    for g, h in zip(old["checkpoints"], new["checkpoints"]):
        for n, gv in g["x"].items():
            if n not in h["x"]:
                continue
            hv = h["x"][n]
            r = abs(hv - gv) / max(abs(gv), 1e-300)
            if r > best[4]:
                best = (g["t"], n, gv, hv, r)
    return best


def truth_errors(name):
    """(old error, new error, truth name)."""
    if name.startswith("analytic__"):
        c = BY_ID[name.removeprefix("analytic__")]
        out = []
        for ctx in (nd.legacy(), _null()):
            with ctx:
                r = c.run("pwl")
            out.append(metrics.err_rms(np.asarray(r.times), c.observe(r), c.exact,
                                       abs_scale=c.abs_scale, exclude_t0=c.exclude_t0))
        return out[0], out[1], "closed form (err_rms)"
    rel = next(r for r in goldens.TRIAGED if Path(r).stem == name)
    case = v1_reader.load(ROOT / "benchmarks" / rel)
    cols = dr.observables_of(case)
    if rel in sb.solved_circuits():
        sol = et.Solver(et.Circuit(ROOT / "benchmarks" / rel), sb.truth_dps(rel)).run()
        g, _, _ = sb.graded_columns(sol, cols)
        sp = sb.spans(sol, g)
        out = []
        for ctx in (nd.legacy(), _null()):
            with ctx:
                r = case.run("pwl")
            out.append(sb.grade(sol, dr.traces(r, cols), g, sp, case.dt, 2e-2, self_score=False)["exact"])
        return out[0], out[1], "mpmath truth (exact measure)"
    with nd.legacy():
        ref = dr.traces(case.run("trbdf2", rtol=1e-10, atol=1e-13), cols)
    out = []
    for ctx in (nd.legacy(), _null()):
        with ctx:
            r = case.run("pwl")
        out.append(dr.compare(dr.traces(r, cols), ref, cols, 1e-3)[0])
    return out[0], out[1], "trbdf2 rtol 1e-10 (not independent)"


def _null():
    import contextlib
    return contextlib.nullcontext()


def main() -> int:
    warnings.simplefilter("ignore")
    rows, worse = [], []
    runs = {n: goldens.snapshot(run(), names, newton) for n, run, names, newton in goldens.cases()}
    names = sorted(runs)
    for name in names:
        old = json.loads((goldens.LEGACY_DIR / f"{name}.json").read_text(encoding="utf-8"))
        new = runs[name]
        if not goldens.compare(old, new) and old["n_steps"] == new["n_steps"]:
            continue
        t, col, ov, nv, r = moved(old, new)
        eo, en, tname = truth_errors(name)
        on_file = json.loads((goldens.GOLDEN_DIR / f"{name}.json").read_text(encoding="utf-8"))
        kept = not goldens.compare(old, on_file)
        if en > eo:   # farther from the truth: never regenerated (the old golden stays on file)
            closer = f"FARTHER ({en / eo:.3g}x){'; old golden kept' if kept else '; REGENERATED'}"
            worse.append(name)
        else:
            closer = "new closer" if en < eo else "equal"
            assert not kept, f"{name}: closer to the truth but its golden was not regenerated"
        rows.append(f"| {name} | t={t:.6g} {col} | {ov:.9g} | {nv:.9g} | {tname} | {eo:.3g} | {en:.3g} | {closer} |")
        print(rows[-1], flush=True)
    L = ["# Release golden diff", "",
         "Generated by `openspec/changes/update-number-changing-release/probes/golden_diff.py` (do not edit).",
         "Every fixed-engine golden (`benchmarks/goldens/pwl/`) the number-changing release changed: the",
         "checkpoint entry that moved most (old = `benchmarks/goldens/pwl_legacy/`, the pre-release",
         "defaults, still checked under `next_defaults.legacy()`; new = the defaults), and the whole run",
         "against its truth under each. `FARTHER`: the new run is farther from its truth than the old;",
         "such a golden is not regenerated (the file keeps the pre-release value) and is reported.", "",
         f"{len(rows)} of {len(names)} goldens changed; {len(worse)} worse against the truth"
         + (f": {', '.join(worse)}." if worse else "."), "",
         "| golden | entry | old | new | truth | old error | new error | verdict |",
         "|---|---|---:|---:|---|---:|---:|---|", *rows]
    OUT.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"wrote {OUT}: {len(rows)} changed, {len(worse)} worse")
    return 1 if worse else 0


if __name__ == "__main__":
    raise SystemExit(main())

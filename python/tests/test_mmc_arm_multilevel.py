class TestStep:
    def test_reject_non_positive_dt(self):
        params = MmcArmMultilevelParams(n_sm=4, c_sm=1e-3)
        with pytest.raises(ValueError, match="dt"):
            mmc_arm_multilevel_step(0.0, 0.5, 1.0, 0.0, 0.0, params)

    def test_v_b_quantized(self):
        """v_b == (s_b / N) · v_C — never anything in between."""
        params = MmcArmMultilevelParams(
            n_sm=4, c_sm=1e-3, f_carrier=1000.0,
        )
        for t in np.linspace(0.0, 1e-3, 31):
            v_C_next, v_b, s_b = mmc_arm_multilevel_step(
                v_C=100.0, m_ref=0.45, i_b=0.0,
                dt=1e-5, t=float(t), params=params,
            )
            assert v_b == pytest.approx((s_b / params.n_sm) * 100.0)


class TestSimulate:
    def test_result_shape(self):
        params = MmcArmMultilevelParams(
            n_sm=8, c_sm=1e-3, v_c0=400.0, f_carrier=1000.0,
        )
        # dt small enough to resolve switching: 1 / (10·N·f) = 12.5 µs
        # → use 5 µs.
        res = simulate_mmc_arm_multilevel(
            duration=1e-3, dt=5e-6,
            m_ref=0.5, i_b=0.0,
            params=params,
        )
        assert isinstance(res, MmcArmMultilevelResult)
        assert res.t.shape == (201,)
        for arr in (res.v_C, res.v_b, res.m_ref, res.s_b, res.i_b):
            assert arr.shape == (201,)
        # s_b is integer-valued.
        assert res.s_b.dtype.kind == "i"
        assert res.params is params

    def test_zero_current_keeps_v_C(self):
        """Even with switching, i_b=0 ⇒ no v_C drift."""
        params = MmcArmMultilevelParams(
            n_sm=8, c_sm=1e-3, v_c0=600.0, f_carrier=1000.0,
        )
        res = simulate_mmc_arm_multilevel(
            duration=2e-3, dt=5e-6,
            m_ref=0.5, i_b=0.0,
            params=params,
        )
        assert np.allclose(res.v_C, 600.0)
        # v_b is a staircase between 0..v_C in N+1 steps.
        unique_levels = set(np.unique(res.v_b))
        # Expected discrete levels: (s_b / N) · 600 for s_b ∈ {0..N}.
        # We don't expect *every* level to appear with constant m=0.5
        # (the PS-PWM only visits adjacent levels around s_b ≈ 4),
        # but every observed level should be exactly s_b/8 · 600.
        for v in unique_levels:
            ratio = v / 600.0
            s_b_eff = ratio * params.n_sm
            assert s_b_eff == pytest.approx(round(s_b_eff), abs=1e-12), (
                f"v_b={v} is not a clean s_b/N·v_C level"
            )

    def test_dc_charging_matches_time_averaged_l0(self):
        """Time-averaged L1 v_C trajectory should track L0 (continuous
        m_b) under a constant reference and constant current."""
        n_sm = 10
        c_sm = 2e-3
        v_c0 = 500.0
        m = 0.5
        i_const = 4.0
        f_carrier = 2000.0
        # dt < 1 / (10·N·f) = 5 µs
        dt = 1e-6
        duration = 2e-3

        params_l1 = MmcArmMultilevelParams(
            n_sm=n_sm, c_sm=c_sm, v_c0=v_c0, f_carrier=f_carrier,
        )
        params_l0 = MmcArmAverageParams(
            n_sm=n_sm, c_sm=c_sm, v_c0=v_c0,
        )
        res_l1 = simulate_mmc_arm_multilevel(
            duration=duration, dt=dt, m_ref=m, i_b=i_const,
            params=params_l1,
        )
        res_l0 = simulate_mmc_arm_average(
            duration=duration, dt=dt, m_b=m, i_b=i_const,
            params=params_l0,
        )

        # Final v_C agreement: L1 charges at the *time-averaged*
        # m_b = m_ref, so its final v_C should match L0 within one
        # bit of resolution (= dt · 1/N · i_const / C_arm per step).
        # Over 2000 steps the accumulated PWM ripple stays bounded
        # at < 1 % of the swing.
        swing = res_l0.v_C[-1] - v_c0
        diff = abs(res_l1.v_C[-1] - res_l0.v_C[-1])
        assert diff <= 0.01 * abs(swing) + 0.5, (
            f"L1 final v_C = {res_l1.v_C[-1]:.4f} differs by "
            f"{diff:.4f} from L0 ({res_l0.v_C[-1]:.4f}); swing was "
            f"{swing:.4f}"
        )

    def test_switching_frequency_at_arm_output(self):
        """v_b transitions per second ≈ 2 · N · f_carrier (each
        carrier fires one rising + one falling edge per carrier
        period). Use m_ref ≠ 0.5 to avoid the EVEN-N degenerate
        case where every rising crossing is paired with a falling
        crossing at the same instant (s_b stays locked at N/2)."""
        n_sm = 6
        f_carrier = 1000.0
        # Resolve the effective switching frequency with margin:
        # dt = 1 / (20 · N · f) = 8.3 µs.
        dt = 5e-6
        duration = 10e-3  # ten carrier periods
        params = MmcArmMultilevelParams(
            n_sm=n_sm, c_sm=1e-3, v_c0=100.0, f_carrier=f_carrier,
        )
        res = simulate_mmc_arm_multilevel(
            duration=duration, dt=dt, m_ref=0.45, i_b=0.0,
            params=params,
        )
        # Count transitions in s_b.
        transitions = int(np.sum(np.diff(res.s_b) != 0))
        # Expected transitions in `duration` = 2·N·f·duration.
        expected = 2 * n_sm * f_carrier * duration
        # ±10 % to absorb sampling-grid quantization (some transitions
        # land in the same dt bucket).
        assert transitions == pytest.approx(expected, rel=0.10), (
            f"transitions={transitions}, expected {expected}"
        )

    def test_m_ref_half_with_even_n_locks_s_b(self):
        """Documented PS-PWM quirk: m_ref = 0.5 with even N produces
        a constant s_b = N/2 because every rising crossing of a
        carrier coincides with a falling crossing of its 180°-shifted
        sibling. Useful sanity check that our implementation
        reproduces this analytical property."""
        n_sm = 6
        params = MmcArmMultilevelParams(
            n_sm=n_sm, c_sm=1e-3, v_c0=100.0, f_carrier=1000.0,
        )
        res = simulate_mmc_arm_multilevel(
            duration=5e-3, dt=5e-6, m_ref=0.5, i_b=0.0,
            params=params,
        )
        # s_b should be N/2 = 3 almost everywhere; a couple of
        # samples drop to 2 due to floating-point timing of paired
        # crossings, but those excursions are < 5 % of samples.
        n_off = int(np.sum(res.s_b != n_sm // 2))
        assert n_off < 0.05 * len(res.s_b), (
            f"PS-PWM m=0.5 should lock at N/2; saw {n_off} off-level "
            f"samples out of {len(res.s_b)}"
        )

    def test_reject_invalid_durations(self):
        params = MmcArmMultilevelParams(n_sm=4, c_sm=1e-3)
        with pytest.raises(ValueError, match="duration"):
            simulate_mmc_arm_multilevel(
                duration=0.0, dt=1e-5, m_ref=0.0, i_b=0.0,
                params=params,
            )
        with pytest.raises(ValueError, match="dt"):
            simulate_mmc_arm_multilevel(
                duration=1e-3, dt=2e-3, m_ref=0.0, i_b=0.0,
                params=params,
            )

    def test_reject_const_m_ref_out_of_range(self):
        """Scalar m_ref outside [m_min, m_max] raises at build time."""
        params = MmcArmMultilevelParams(n_sm=4, c_sm=1e-3)
        with pytest.raises(ValueError, match="outside valid range"):
            simulate_mmc_arm_multilevel(
                duration=1e-3, dt=1e-5, m_ref=-0.1, i_b=0.0,
                params=params,
            )

    def test_full_bridge_negative_modulation(self):
        """FB with negative m_ref produces negative s_b and negative v_b."""
        params = MmcArmMultilevelParams(
            n_sm=4, c_sm=1e-3, sm_type="full_bridge",
            v_c0=400.0, f_carrier=1000.0,
        )
        res = simulate_mmc_arm_multilevel(
            duration=1e-3, dt=5e-6, m_ref=-0.5, i_b=0.0,
            params=params,
        )
        # All s_b values should be ≤ 0 for m_ref < 0.
        assert (res.s_b <= 0).all()
        assert (res.s_b >= -params.n_sm).all()
        # v_b ≤ 0 (m_ref < 0 ⇒ v_b = (negative s_b/N) · v_C).
        assert (res.v_b <= 0).all()

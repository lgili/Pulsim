class TestParams:
    def test_defaults(self):
        p = MmcArmMultilevelParams(n_sm=8, c_sm=1e-3)
        assert p.n_sm == 8
        assert p.c_sm == 1e-3
        assert p.sm_type == "half_bridge"
        assert p.v_c0 == 0.0
        assert p.r_p is None
        assert p.f_carrier == 1000.0
        assert p.c_arm == pytest.approx(1.25e-4)
        assert p.f_switch == pytest.approx(8000.0)
        assert p.m_min == 0.0
        assert p.m_max == 1.0

    def test_full_bridge(self):
        p = MmcArmMultilevelParams(
            n_sm=4, c_sm=1e-3, sm_type="full_bridge", f_carrier=2000.0,
        )
        assert p.m_min == -1.0
        assert p.m_max == 1.0
        assert p.f_switch == 8000.0

    def test_reject_zero_n_sm(self):
        with pytest.raises(ValueError, match="n_sm"):
            MmcArmMultilevelParams(n_sm=0, c_sm=1e-3)

    def test_reject_non_positive_c_sm(self):
        with pytest.raises(ValueError, match="c_sm"):
            MmcArmMultilevelParams(n_sm=4, c_sm=-1e-6)

    def test_reject_unknown_sm_type(self):
        with pytest.raises(ValueError, match="sm_type"):
            MmcArmMultilevelParams(  # type: ignore[arg-type]
                n_sm=4, c_sm=1e-3, sm_type="quarter",
            )

    def test_reject_non_positive_r_p(self):
        with pytest.raises(ValueError, match="r_p"):
            MmcArmMultilevelParams(n_sm=4, c_sm=1e-3, r_p=0.0)

    def test_reject_non_positive_f_carrier(self):
        with pytest.raises(ValueError, match="f_carrier"):
            MmcArmMultilevelParams(n_sm=4, c_sm=1e-3, f_carrier=0.0)



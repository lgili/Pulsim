"""Validation tests for the L1 MMC multilevel-arm model.

L1 replaces L0's continuous ``m_b`` with a quantized ``s_b ∈ {0..N}``
generated by phase-shifted PWM. The dynamics are mathematically
identical (eqs 2.9 ≡ 2.14 with m_b ≡ s_b/N); the only new physics is
the staircase ``v_b(t)`` and the high-frequency switching ripple it
puts on top of the L0 envelope.

What we verify:

  * **Quantizer range.** s_b ∈ {0..N} for HB, {-N..N} for FB, for any
    m_ref (out-of-range inputs are silently clamped).
  * **Time-averaged duty.** Over one carrier period, the average of
    s_b/N tracks the constant m_ref within one bit.
  * **Multilevel output.** v_b takes at most N+1 distinct levels and
    each level appears at least once for a representative sweep.
  * **Effective switching frequency.** The number of s_b transitions
    per carrier period equals 2N for HB (each of N carriers fires a
    rising and a falling edge per period).
  * **L1 → L0 envelope convergence.** Low-pass-filter L1's v_b at a
    cutoff well below ``f_carrier`` and confirm it tracks L0's v_b
    (continuous-m_b case) within < 2 % at the same m_ref.
  * **Parameter contract guard rails.**
"""

from __future__ import annotations

import numpy as np
import pytest

from pulsim.mmc import (
    MmcArmAverageParams,
    MmcArmMultilevelParams,
    MmcArmMultilevelResult,
    mmc_arm_multilevel_step,
    ps_pwm_switching_function,
    simulate_mmc_arm_average,
    simulate_mmc_arm_multilevel,
)



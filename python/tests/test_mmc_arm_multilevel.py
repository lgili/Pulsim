class TestQuantizer:
    """Direct tests of ps_pwm_switching_function()."""

    @pytest.mark.parametrize("n_sm", [1, 4, 10, 30])
    def test_hb_range(self, n_sm):
        """HB s_b ∈ {0..N} for any t and m_ref ∈ [0, 1]."""
        for m_ref in [0.0, 0.1, 0.5, 0.9, 1.0]:
            for t in np.linspace(0.0, 1e-3, 27):
                s = ps_pwm_switching_function(
                    m_ref, float(t), n_sm, 1000.0,
                    sm_type="half_bridge",
                )
                assert 0 <= s <= n_sm, (
                    f"HB s_b={s} out of range [0,{n_sm}] "
                    f"at t={t}, m={m_ref}"
                )

    @pytest.mark.parametrize("n_sm", [1, 4, 10])
    def test_fb_range(self, n_sm):
        """FB s_b ∈ {-N..N} with sign tracking m_ref."""
        for m_ref in [-1.0, -0.5, 0.0, 0.3, 1.0]:
            for t in np.linspace(0.0, 1e-3, 27):
                s = ps_pwm_switching_function(
                    m_ref, float(t), n_sm, 1000.0,
                    sm_type="full_bridge",
                )
                assert -n_sm <= s <= n_sm
                if m_ref > 0:
                    assert s >= 0
                elif m_ref < 0:
                    assert s <= 0

    def test_clamps_out_of_range_silently(self):
        """Out-of-range m_ref is clamped — no exception (hot loop)."""
        # HB clamps to [0, 1].
        # Below-range → 0 fires (m clamped to 0, strict m > tri is
        # always false at tri ≥ 0).
        assert ps_pwm_switching_function(
            -0.5, 0.0, 4, 1000.0, sm_type="half_bridge",
        ) == 0
        # Above-range → all SMs fire EXCEPT any carrier that happens
        # to sit at the peak (tri = 1.0) at the sampled instant (m > 1.0
        # is false when m clamps to 1.0). Off the peak, all N fire.
        # Use a non-singular time to get the clean N-bit result:
        n = 8
        assert ps_pwm_switching_function(
            2.0, 1e-7, n, 1000.0, sm_type="half_bridge",
        ) == n

    def test_time_averaged_duty_tracks_m_ref(self):
        """Over one carrier period, mean(s_b)/N should equal m_ref
        within one bit (= 1/N)."""
        n_sm = 10
        f = 1000.0
        T = 1.0 / f
        for m_ref in [0.1, 0.3, 0.5, 0.7, 0.9]:
            ts = np.linspace(0.0, T, 1001, endpoint=False)
            s_values = [
                ps_pwm_switching_function(
                    m_ref, float(t), n_sm, f, sm_type="half_bridge",
                )
                for t in ts
            ]
            mean = float(np.mean(s_values)) / n_sm
            # One-bit tolerance plus a small numerical margin for
            # the finite-sample average.
            assert abs(mean - m_ref) <= 1.0 / n_sm + 1e-3, (
                f"m_ref={m_ref}: mean(s_b)/N = {mean:.4f}"
            )

    def test_n_levels_observed_equals_n_plus_1(self):
        """Sweeping m_ref over [0, 1] visits every level 0..N."""
        n_sm = 8
        f = 1000.0
        T = 1.0 / f
        seen: set[int] = set()
        for m_ref in np.linspace(0.0, 1.0, 51):
            for t in np.linspace(0.0, T, 101, endpoint=False):
                s = ps_pwm_switching_function(
                    float(m_ref), float(t), n_sm, f,
                    sm_type="half_bridge",
                )
                seen.add(s)
        assert seen == set(range(n_sm + 1))

    def test_constant_m_ref_periodic_in_carrier(self):
        """Constant m_ref ⇒ s_b(t) is periodic with period 1/f."""
        n_sm = 6
        f = 5000.0
        T = 1.0 / f
        m_ref = 0.45
        # Sample s_b at t and t+T; should agree.
        for t0 in np.linspace(0.0, 1e-3, 17):
            s1 = ps_pwm_switching_function(
                m_ref, float(t0), n_sm, f, sm_type="half_bridge",
            )
            s2 = ps_pwm_switching_function(
                m_ref, float(t0 + T), n_sm, f, sm_type="half_bridge",
            )
            assert s1 == s2



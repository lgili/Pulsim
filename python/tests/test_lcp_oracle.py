"""add-complementarity-mode-selection task 1.1: the test-only LCP oracle agrees with itself.

Lemke (lexicographic) against 2^k enumeration on random PSD instances, and on the LCPs the
prototype posed on the five circuit families (fixtures generated by
openspec/changes/add-complementarity-mode-selection/probes/dump_lcp_instances.py).
"""
import json
import os

import numpy as np
import pytest

pytest.importorskip("scipy")
from tests.oracles import lcp_reference as L  # noqa: E402

HERE = os.path.dirname(__file__)
INSTANCES = json.load(open(os.path.join(HERE, "oracles", "lcp_instances.json")))


def _valid(M, q, z, w, tol=1e-8):
    sc = max(1.0, np.abs(q).max(), np.abs(z).max())
    return (z.min() >= -tol * sc and w.min() >= -tol * sc
            and np.abs(z * w).max() <= tol * sc * sc
            and np.abs(M @ z + q - w).max() <= tol * sc * max(1.0, np.abs(M).max()))


def _random_psd(rng, k, definite):
    A = rng.standard_normal((k, k))
    if not definite:
        A[:, rng.integers(k)] = 0.0              # rank-deficient symmetric part
    S = rng.standard_normal((k, k))
    M = A @ A.T + (S - S.T)                      # PSD in the non-symmetric sense
    if definite:
        M += 1e-2 * np.eye(k)
    return M, 3.0 * rng.standard_normal(k)


def test_lemke_matches_enumeration_on_200_random_psd_instances():
    rng = np.random.default_rng(20261113)
    solved = unique_same = 0
    for n in range(200):
        k = 1 + n % 8
        M, q = _random_psd(rng, k, definite=n % 2 == 0)
        z, w, piv, status = L.lemke(M, q)
        sols = L.enumerate_lcp(M, q)
        if status == "secondary ray":
            assert not sols, "Lemke reported no solution where enumeration found one"
            continue
        assert status in ("solution", "trivial")
        assert _valid(M, q, z, w)
        assert sols, "enumeration missed a solution Lemke found"
        solved += 1
        if n % 2 == 0:                            # positive definite: a P-matrix, unique solution
            assert len(sols) == 1
            np.testing.assert_allclose(sols[0][0], z, rtol=1e-8, atol=1e-8)
            unique_same += 1
    assert solved >= 180 and unique_same == 100


@pytest.mark.parametrize("fam", sorted({o["family"] for o in INSTANCES}))
def test_lemke_and_enumeration_agree_on_the_family_lcps(fam):
    rows = [o for o in INSTANCES if o["family"] == fam]
    assert rows
    for o in rows:
        M, q = np.array(o["M"]), np.array(o["q"])
        z, w, piv, status = L.lemke(M, q)
        assert piv == o["pivots"] and status == o["status"]
        assert _valid(M, q, z, w)
        sols = L.enumerate_lcp(M, q)
        assert sols
        # the Lemke solution is one of the enumerated complementary solutions
        sc = max(1.0, np.abs(z).max(), np.abs(q).max())
        assert any(np.abs(s[0] - z).max() <= 1e-7 * sc for s in sols)

"""Modular Multilevel Converter (MMC) models.

Phase 20 — L0 of the layered MMC block hierarchy. This module ships the
**average-value arm model**: one state per arm (``v_C``, the sum of the
submodule capacitor voltages), continuous modulation index
``m_b ∈ [0, 1]`` (half-bridge) or ``m_b ∈ [-1, 1]`` (full-bridge), and
forward-Euler integration of the capacitor dynamics.

Reference
=========

Sousa, Gean Jacques Maia de.
*Sistemas de Controle para a Operação Eficiente de Conversores
Modulares Multiníveis em Acionamentos Elétricos.*
PhD thesis, UFSC, 2022. — ``artigos/Gean Jacques Maia de Sousa.pdf``

Average-arm equations (thesis eqs 2.13, 2.14)
=============================================

With per-submodule capacitance ``C_SM`` and ``N`` submodules per arm,
define the arm-equivalent capacitance ``C = C_SM / N`` and the
modulation index ``m_b = s_b / N`` (where ``s_b ∈ {0..N}`` is the
multilevel switching function). The averaged dynamics become

.. math::

    v_b = m_b \\cdot v_C
    \\\\
    \\frac{dv_C}{dt} = \\frac{1}{C} \\cdot m_b \\cdot i_b

with ``v_b`` the voltage generated by the arm and ``i_b`` the current
flowing through it.

This is mathematically identical to an *ideal transformer with turns
ratio* ``m_b : 1`` feeding the equivalent capacitor ``C`` (thesis
fig 2.6). L0 implements that abstraction directly as an explicit ODE
in Python.

API
===

* :class:`MmcArmAverageParams` — config (N, C_SM, type, initial v_C, ...).
* :class:`MmcArmAverageResult` — simulation output (time series).
* :func:`simulate_mmc_arm_average` — drive the average arm model
  over a duration with user-supplied ``m_b(t)`` and ``i_b(t)``.
* :func:`mmc_arm_average_step` — pure one-step advance (for users who
  want to embed the arm in their own outer loop).

The L1 (discrete multilevel), L2 (SM-equivalent with dead-time +
min-pulse-width), and L3 (per-SM detailed) blocks live in follow-up
phases. See ``docs/internals/mmc-arm-block.md`` for the full roadmap.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Callable, Literal

import numpy as np

__all__ = [
    "MmcArmAverageParams",
    "MmcArmAverageResult",
    "mmc_arm_average_step",
    "simulate_mmc_arm_average",
]


SubmoduleType = Literal["half_bridge", "full_bridge"]


# ----------------------------------------------------------------------
# Parameter contract
# ----------------------------------------------------------------------

@dataclass(frozen=True)
class MmcArmAverageParams:
    """Configuration for the L0 average-arm model.

    Attributes:
        n_sm: Number of submodules per arm (≥ 1).
        c_sm: Capacitance of one submodule [F]. The arm-equivalent
            capacitance is ``C = c_sm / n_sm``.
        sm_type: ``"half_bridge"`` (m_b ∈ [0, 1]) or
            ``"full_bridge"`` (m_b ∈ [-1, 1]).
        v_c0: Initial capacitor-sum voltage [V] (``v_C(0)``).
        r_p: Optional parallel loss resistance across the equivalent
            capacitor [Ω]. ``None`` (default) ⇒ lossless. When set, the
            dynamics become
            ``dv_C/dt = (m_b · i_b - v_C / r_p) / C``,
            matching thesis eq (3.99) sans the auxiliary-supply term.
    """

    n_sm: int
    c_sm: float
    sm_type: SubmoduleType = "half_bridge"
    v_c0: float = 0.0
    r_p: float | None = None

    def __post_init__(self) -> None:
        if self.n_sm < 1:
            raise ValueError(f"n_sm must be ≥ 1 (got {self.n_sm})")
        if self.c_sm <= 0:
            raise ValueError(f"c_sm must be > 0 (got {self.c_sm})")
        if self.sm_type not in ("half_bridge", "full_bridge"):
            raise ValueError(
                f"sm_type must be 'half_bridge' or 'full_bridge' "
                f"(got {self.sm_type!r})"
            )
        if self.r_p is not None and self.r_p <= 0:
            raise ValueError(f"r_p must be > 0 when set (got {self.r_p})")

    @property
    def c_arm(self) -> float:
        """Arm-equivalent capacitance C = c_sm / n_sm [F]."""
        return self.c_sm / self.n_sm

    @property
    def m_min(self) -> float:
        """Minimum valid modulation index (0 for HB, -1 for FB)."""
        return 0.0 if self.sm_type == "half_bridge" else -1.0

    @property
    def m_max(self) -> float:
        """Maximum valid modulation index (1 for both topologies)."""
        return 1.0


# ----------------------------------------------------------------------
# Step function — the single source of truth for the dynamics
# ----------------------------------------------------------------------

def mmc_arm_average_step(
    v_C: float,
    m_b: float,
    i_b: float,
    dt: float,
    params: MmcArmAverageParams,
) -> tuple[float, float]:
    """Advance the L0 average-arm model by one forward-Euler step.

    Args:
        v_C: Current arm-equivalent capacitor voltage [V].
        m_b: Modulation index for this step (range depends on
            ``params.sm_type``).
        i_b: Arm current at this step [A].
        dt: Time step [s] (must be > 0).
        params: Arm configuration.

    Returns:
        ``(v_C_next, v_b)``:
            * ``v_C_next`` — capacitor-sum voltage after ``dt``.
            * ``v_b`` — voltage generated by the arm at this step
              (``m_b · v_C``).

    Notes:
        Forward-Euler is sufficient for the average model because the
        capacitor pole sits at ``1 / (R_p · C)`` (typically << 1 kHz),
        far below typical simulation step rates. Use a smaller step
        only if you also resolve the high-frequency modulation content
        in ``m_b(t)``.
    """
    if dt <= 0:
        raise ValueError(f"dt must be > 0 (got {dt})")

    v_b = m_b * v_C
    # dv_C/dt = (m_b · i_b - v_C / R_p) / C
    leak = (v_C / params.r_p) if params.r_p is not None else 0.0
    dv_dt = (m_b * i_b - leak) / params.c_arm
    v_C_next = v_C + dt * dv_dt
    return v_C_next, v_b


# ----------------------------------------------------------------------
# Time-series driver
# ----------------------------------------------------------------------

@dataclass(frozen=True)
class MmcArmAverageResult:
    """Output of :func:`simulate_mmc_arm_average`.

    All arrays share the same shape ``(N + 1,)`` where ``N = duration / dt``
    (rounded).

    Attributes:
        t: Time vector [s].
        v_C: Capacitor-sum voltage trajectory [V].
        v_b: Arm-generated voltage trajectory [V].
        m_b: Applied modulation index trajectory.
        i_b: Arm current trajectory [A].
        params: Parameters used for the run (echoed for traceability).
    """

    t: np.ndarray
    v_C: np.ndarray
    v_b: np.ndarray
    m_b: np.ndarray
    i_b: np.ndarray
    params: MmcArmAverageParams = field(repr=False)


def simulate_mmc_arm_average(
    *,
    duration: float,
    dt: float,
    m_b: float | Callable[[float], float],
    i_b: float | Callable[[float], float],
    params: MmcArmAverageParams,
) -> MmcArmAverageResult:
    """Run the L0 average-arm model over ``[0, duration]``.

    Args:
        duration: Simulation length [s] (must be > 0).
        dt: Fixed time step [s] (must be > 0 and < duration).
        m_b: Modulation index. Pass a scalar for a constant signal or
            a callable ``t -> m_b`` for time-varying input.
        i_b: Arm current [A]. Same shape as ``m_b``: scalar or callable.
        params: Arm configuration.

    Returns:
        A :class:`MmcArmAverageResult` with the full trajectories.

    Raises:
        ValueError: If ``duration`` or ``dt`` are non-positive, or if
            ``m_b`` ever lies outside ``[params.m_min, params.m_max]``.
    """
    if duration <= 0:
        raise ValueError(f"duration must be > 0 (got {duration})")
    if dt <= 0 or dt > duration:
        raise ValueError(f"dt must be in (0, duration] (got {dt})")

    n_steps = int(np.floor(duration / dt))
    n_points = n_steps + 1
    t = np.arange(n_points) * dt

    m_b_fn = (lambda _t, _v=float(m_b): _v) if not callable(m_b) else m_b
    i_b_fn = (lambda _t, _v=float(i_b): _v) if not callable(i_b) else i_b

    v_C_arr = np.zeros(n_points)
    v_b_arr = np.zeros(n_points)
    m_b_arr = np.zeros(n_points)
    i_b_arr = np.zeros(n_points)

    v_C = float(params.v_c0)
    for k, tk in enumerate(t):
        m_k = float(m_b_fn(tk))
        i_k = float(i_b_fn(tk))
        if m_k < params.m_min or m_k > params.m_max:
            raise ValueError(
                f"m_b={m_k:.4f} at t={tk:.6f}s outside valid range "
                f"[{params.m_min}, {params.m_max}] for "
                f"sm_type={params.sm_type!r}"
            )
        m_b_arr[k] = m_k
        i_b_arr[k] = i_k
        v_C_arr[k] = v_C
        v_b_arr[k] = m_k * v_C
        if k < n_points - 1:
            v_C, _ = mmc_arm_average_step(v_C, m_k, i_k, dt, params)

    return MmcArmAverageResult(
        t=t,
        v_C=v_C_arr,
        v_b=v_b_arr,
        m_b=m_b_arr,
        i_b=i_b_arr,
        params=params,
    )

# Parameter contract
# ----------------------------------------------------------------------

@dataclass(frozen=True)
class MmcArmAverageParams:
    """Configuration for the L0 average-arm model.

    Attributes:
        n_sm: Number of submodules per arm (≥ 1).
        c_sm: Capacitance of one submodule [F]. The arm-equivalent
            capacitance is ``C = c_sm / n_sm``.
        sm_type: ``"half_bridge"`` (m_b ∈ [0, 1]) or
            ``"full_bridge"`` (m_b ∈ [-1, 1]).
        v_c0: Initial capacitor-sum voltage [V] (``v_C(0)``).
        r_p: Optional parallel loss resistance across the equivalent
            capacitor [Ω]. ``None`` (default) ⇒ lossless. When set, the
            dynamics become
            ``dv_C/dt = (m_b · i_b - v_C / r_p) / C``,
            matching thesis eq (3.99) sans the auxiliary-supply term.
    """

    n_sm: int
    c_sm: float
    sm_type: SubmoduleType = "half_bridge"
    v_c0: float = 0.0
    r_p: float | None = None

    def __post_init__(self) -> None:
        if self.n_sm < 1:
            raise ValueError(f"n_sm must be ≥ 1 (got {self.n_sm})")
        if self.c_sm <= 0:
            raise ValueError(f"c_sm must be > 0 (got {self.c_sm})")
        if self.sm_type not in ("half_bridge", "full_bridge"):
            raise ValueError(
                f"sm_type must be 'half_bridge' or 'full_bridge' "
                f"(got {self.sm_type!r})"
            )
        if self.r_p is not None and self.r_p <= 0:
            raise ValueError(f"r_p must be > 0 when set (got {self.r_p})")

    @property
    def c_arm(self) -> float:
        """Arm-equivalent capacitance C = c_sm / n_sm [F]."""
        return self.c_sm / self.n_sm

    @property
    def m_min(self) -> float:
        """Minimum valid modulation index (0 for HB, -1 for FB)."""
        return 0.0 if self.sm_type == "half_bridge" else -1.0

    @property
    def m_max(self) -> float:
        """Maximum valid modulation index (1 for both topologies)."""
        return 1.0


# ----------------------------------------------------------------------
# Step function — the single source of truth for the dynamics
# ----------------------------------------------------------------------

def mmc_arm_average_step(
    v_C: float,
    m_b: float,
    i_b: float,
    dt: float,
    params: MmcArmAverageParams,
) -> tuple[float, float]:
    """Advance the L0 average-arm model by one forward-Euler step.

    Args:
        v_C: Current arm-equivalent capacitor voltage [V].
        m_b: Modulation index for this step (range depends on
            ``params.sm_type``).
        i_b: Arm current at this step [A].
        dt: Time step [s] (must be > 0).
        params: Arm configuration.

    Returns:
        ``(v_C_next, v_b)``:
            * ``v_C_next`` — capacitor-sum voltage after ``dt``.
            * ``v_b`` — voltage generated by the arm at this step
              (``m_b · v_C``).

    Notes:
        Forward-Euler is sufficient for the average model because the
        capacitor pole sits at ``1 / (R_p · C)`` (typically << 1 kHz),
        far below typical simulation step rates. Use a smaller step
        only if you also resolve the high-frequency modulation content
        in ``m_b(t)``.
    """
    if dt <= 0:
        raise ValueError(f"dt must be > 0 (got {dt})")

    v_b = m_b * v_C
    # dv_C/dt = (m_b · i_b - v_C / R_p) / C
    leak = (v_C / params.r_p) if params.r_p is not None else 0.0
    dv_dt = (m_b * i_b - leak) / params.c_arm
    v_C_next = v_C + dt * dv_dt
    return v_C_next, v_b



#!/usr/bin/env python3
"""Generate the type stub ``python/pulsim/_pulsim.pyi`` for the native module.

``pulsim._pulsim`` is a pybind11 extension. Its callables have no
inspectable signature (``inspect.signature`` raises ``ValueError``); the
signature lives only on the first line of ``__doc__``. IDEs, type
checkers and AI assistants therefore guess argument names and order
unless a ``.pyi`` ships next to the extension. This script produces it:

1. runs the pinned ``pybind11-stubgen`` on the BUILT extension;
2. post-processes the few constructs it cannot print as valid Python
   (each rule below says why it exists and when it can go);
3. merges ``scripts/stubs_overlay.pyi`` -- the members the pure-Python
   layer attaches to native classes (``SimulationResult.v`` ...);
4. writes ``python/pulsim/_pulsim.pyi``.

Usage::

    python scripts/generate_stubs.py            # regenerate in place
    python scripts/generate_stubs.py --check    # exit 1 + diff if stale

Requirements: a built extension importable as ``pulsim._pulsim`` and
``pip install "pybind11-stubgen==<STUBGEN_VERSION>"`` (in the ``dev``
extra). The dependency-free freshness test is
``python/tests/test_stubs.py``; this script's ``--check`` is the exact,
byte-for-byte check and is version-sensitive by nature, so it insists on
the pinned stubgen version.
"""

from __future__ import annotations

import argparse
import ast
import difflib
import io
import os
import re
import subprocess
import sys
import tempfile
import tokenize
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STUB_PATH = ROOT / "python" / "pulsim" / "_pulsim.pyi"
OVERLAY_PATH = ROOT / "scripts" / "stubs_overlay.pyi"
MODULE = "pulsim._pulsim"

# Pinned: stubgen output changes between releases, and --check is a
# byte-for-byte comparison. Bump together with the ``dev`` extra in
# pyproject.toml, then regenerate.
STUBGEN_VERSION = "3.0.0"

STUBGEN_FLAGS = [
    "--exit-code",
    # numpy/Eigen arrays as ``numpy.ndarray[tuple[M, Literal[1]], dtype]``
    # instead of the non-Python ``numpy.ndarray[numpy.float64[m, 1]]``.
    "--numpy-array-use-type-var",
    # Enum defaults render as ``<DCStrategy.Auto: 0>``; tell stubgen
    # where the enum class lives so it prints ``DCStrategy.Auto``.
    "--enum-class-locations", "DCStrategy:pulsim._pulsim",
    "--enum-class-locations", "ParametricRefactorMode:pulsim._pulsim",
    # Print the expressions matched by KNOWN_INVALID_EXPRESSIONS as-is
    # so the rules below can rewrite them deterministically (stubgen
    # would otherwise replace the TYPE with ``...``, losing it).
    "--print-invalid-expressions-as-is",
]

# Expressions in ``__doc__`` signatures that are not valid Python. They
# come from the bindings and are tolerated here, then rewritten by
# ``_rewrite_cpp_names`` / ``_rewrite_object_reprs``. Any OTHER invalid
# expression still fails the run (``--exit-code``), so a new binding
# with a raw C++ type is caught. Once ``python/bindings.cpp`` registers
# the classes before use and gives ``py::arg_v`` readable defaults
# (openspec change add-ai-usage-guide, tasks 1.1/1.2) these patterns
# match nothing and can be deleted.
KNOWN_INVALID_EXPRESSIONS = [
    # Property / parameter types of classes registered after their use:
    # pulsim::topology::Graph, pulsim::pwl::DevicePool, ...
    r"pulsim::[A-Za-z_:]+",
    # Non-literal defaults: <pulsim._pulsim.PreflightOptions object at 0x...>
    r"<pulsim\._pulsim\.\w+ object at 0x[0-9a-fA-F]+>",
]

HEADER = (
    "# Generated by scripts/generate_stubs.py (pybind11-stubgen {version}).\n"
    "# Do not edit by hand: change python/bindings.cpp or\n"
    "# scripts/stubs_overlay.pyi and regenerate.\n"
)
OVERLAY_MARKER = (
    "    # --- members attached by the pulsim Python layer "
    "(scripts/stubs_overlay.pyi) ---"
)


class StubError(RuntimeError):
    """The stub could not be produced as valid, complete Python."""


# ---------------------------------------------------------------------------
# Running stubgen
# ---------------------------------------------------------------------------
def _default_pythonpath() -> list[str]:
    """Prefer the in-repo package when it holds a built extension.

    ``python/pulsim`` (developer builds copy the extension there) and
    ``build/python`` (the CMake build tree) are tried in order. If
    neither has an extension, the environment's installed ``pulsim``
    is used unchanged (CI installs the wheel with ``pip install .``).
    """
    for cand in (ROOT / "python", ROOT / "build" / "python"):
        pkg = cand / "pulsim"
        if any(pkg.glob("_pulsim*.so")) or any(pkg.glob("_pulsim*.pyd")):
            return [str(cand)]
    return []


def _check_stubgen_version() -> None:
    try:
        from importlib.metadata import version
        found = version("pybind11-stubgen")
    except Exception as exc:  # PackageNotFoundError and friends
        raise StubError(
            "pybind11-stubgen is not installed; "
            f'pip install "pybind11-stubgen=={STUBGEN_VERSION}"'
        ) from exc
    if found != STUBGEN_VERSION:
        raise StubError(
            f"pybind11-stubgen {found} is installed but the stub is pinned "
            f"to {STUBGEN_VERSION}; output differs between versions. "
            f'pip install "pybind11-stubgen=={STUBGEN_VERSION}"'
        )


def run_stubgen(pythonpath: list[str]) -> str:
    """Run stubgen on the built module and return the raw stub text."""
    _check_stubgen_version()
    env = dict(os.environ)
    if pythonpath:
        env["PYTHONPATH"] = os.pathsep.join(
            pythonpath + [p for p in [env.get("PYTHONPATH", "")] if p])
    # Plotting/backends must not open windows while pulsim imports.
    env.setdefault("MPLBACKEND", "Agg")
    with tempfile.TemporaryDirectory() as tmp:
        cmd = [
            sys.executable, "-m", "pybind11_stubgen", MODULE,
            "-o", tmp,
            *STUBGEN_FLAGS,
            "--ignore-invalid-expressions",
            "|".join(f"(?:{p})" for p in KNOWN_INVALID_EXPRESSIONS),
        ]
        proc = subprocess.run(cmd, env=env, capture_output=True, text=True)
        if proc.returncode != 0:
            raise StubError(
                "pybind11-stubgen failed (exit "
                f"{proc.returncode}):\n{proc.stderr}{proc.stdout}")
        out = Path(tmp) / "pulsim" / "_pulsim.pyi"
        if not out.is_file():
            raise StubError(f"stubgen wrote no {out.name}; stderr:\n{proc.stderr}")
        return out.read_text(encoding="utf-8")


# ---------------------------------------------------------------------------
# Post-processing rules
# ---------------------------------------------------------------------------
_FIXED_SIZE_RE = re.compile(
    r"typing\.Annotated\[(?P<inner>[^\[\]]*(?:\[[^\[\]]*\])?), "
    r"pybind11_stubgen\.typing_ext\.FixedSize\(\d+\)\]")
_OBJECT_REPR_RE = re.compile(r"<pulsim\._pulsim\.\w+ object at 0x[0-9a-fA-F]+>")
_CPP_NAME_RE = re.compile(r"\bpulsim::(?:[A-Za-z_]\w*::)*(?P<name>[A-Za-z_]\w*)")
_DEF_RE = re.compile(r"^(?P<head>\s*def \w+\()(?P<params>.*)(?P<tail>\)(?: -> .*)?:\s*)$")


def _strip_fixed_size(text: str) -> tuple[str, int]:
    """``std::array<int, 3>`` -> ``list[int]``.

    stubgen renders it as ``Annotated[list[int], FixedSize(3)]`` with a
    marker class from ``pybind11_stubgen.typing_ext``. A shipped stub
    must not import the generator (it is not a runtime dependency).
    """
    text, n = _FIXED_SIZE_RE.subn(r"\g<inner>", text)
    text = re.sub(r"(?m)^import pybind11_stubgen\.typing_ext\n", "", text)
    return text, n


def _rewrite_object_reprs(text: str) -> tuple[str, int]:
    """A default printed as ``<... object at 0x...>`` becomes ``...``.

    ``...`` is the conventional stub default: the parameter keeps "has a
    default" (what callers need) and the stub stops depending on a
    memory address, which changed on every run.
    """
    return _OBJECT_REPR_RE.subn("...", text)


def _top_level_classes(text: str) -> set[str]:
    return set(re.findall(r"(?m)^class (\w+)\b", text))


def _rewrite_cpp_names(text: str) -> tuple[str, int]:
    """``pulsim::topology::Graph`` -> ``Graph`` when ``Graph`` is bound."""
    classes = _top_level_classes(text)
    unknown: set[str] = set()

    def repl(m: re.Match[str]) -> str:
        name = m.group("name")
        if name not in classes:
            unknown.add(m.group(0))
            return m.group(0)
        return name

    # Signature lines only: docstrings legitimately mention C++
    # (``InputRef::Node``). stubgen writes every ``def`` (properties
    # included) on one physical line. A C++ name anywhere else in code
    # still fails ``validate``.
    out_lines = []
    count = 0
    for line in text.splitlines(keepends=True):
        if line.lstrip().startswith("def "):
            line, n = _CPP_NAME_RE.subn(repl, line)
            count += n
        out_lines.append(line)
    if unknown:
        raise StubError(
            "C++ type names with no bound Python class: "
            + ", ".join(sorted(unknown)))
    return "".join(out_lines), count


def _split_top_level(params: str) -> list[str]:
    """Split a parameter list on commas outside brackets and strings."""
    parts: list[str] = []
    depth = 0
    quote: str | None = None
    start = 0
    i = 0
    while i < len(params):
        ch = params[i]
        if quote:
            if ch == "\\":
                i += 2
                continue
            if ch == quote:
                quote = None
        elif ch in "'\"":
            quote = ch
        elif ch in "([{":
            depth += 1
        elif ch in ")]}":
            depth -= 1
        elif ch == "," and depth == 0:
            parts.append(params[start:i].strip())
            start = i + 1
        i += 1
    tail = params[start:].strip()
    if tail:
        parts.append(tail)
    return parts


def _split_param(param: str) -> tuple[str, str | None, str | None]:
    """``name: ann = default`` -> (name, ann, default); markers pass through."""
    head, default = param, None
    depth = 0
    for i, ch in enumerate(param):
        if ch in "([{":
            depth += 1
        elif ch in ")]}":
            depth -= 1
        elif ch == "=" and depth == 0:
            head, default = param[:i].strip(), param[i + 1:].strip()
            break
    if ":" in head:
        name, ann = head.split(":", 1)
        return name.strip(), ann.strip(), default
    return head.strip(), None, default


def _accepts_none(ann: str) -> bool:
    """True if annotation ``ann`` already admits ``None``.

    Only top-level union members count: ``Callable[[float], None]``
    does NOT accept None, ``Callable[...] | None`` does.
    """
    if ann in ("typing.Any", "object", "None"):
        return True
    if ann.startswith(("typing.Optional[", "Optional[")):
        return True
    depth = 0
    member_start = 0
    members = []
    for i, ch in enumerate(ann):
        if ch in "([{":
            depth += 1
        elif ch in ")]}":
            depth -= 1
        elif ch == "|" and depth == 0:
            members.append(ann[member_start:i].strip())
            member_start = i + 1
    members.append(ann[member_start:].strip())
    return "None" in members


def _fix_eq_ne(text: str) -> tuple[str, int]:
    """``__eq__(self, arg0: X)`` -> ``__eq__(self, arg0: object)``.

    pybind11 prints the bound C++ operand type, which narrows
    ``object.__eq__`` (mypy: Liskov violation in every class that binds
    ``==``). At runtime pybind returns ``NotImplemented`` for a foreign
    operand -- exactly ``object``'s contract.
    """
    return re.subn(
        r"(?m)^(?P<head>\s+def __(?:eq|ne)__\(self, \w+: )[^)]+(?P<tail>\) -> bool:)",
        r"\g<head>object\g<tail>", text)


def _bind_attribute_typevars(text: str) -> tuple[str, int]:
    """Array shape TypeVars in attribute annotations -> ``int``.

    ``--numpy-array-use-type-var`` writes Eigen vectors as
    ``ndarray[tuple[M, Literal[1]], ...]``. In a function signature the
    TypeVar is bound by the call; in a class attribute (a
    ``def_readwrite`` field such as ``SolverSnapshot.x``) it is unbound,
    which mypy rejects. The shape is still "some int" there.
    """
    out_lines = []
    count = 0
    for line in text.splitlines(keepends=True):
        if re.match(r"^\s+\w+: .*numpy\.ndarray\[tuple\[", line):
            line, n = re.subn(
                r"numpy\.ndarray\[tuple\[(?P<dims>[^\[\]]*(?:\[[^\[\]]*\][^\[\]]*)*)\]",
                lambda m: "numpy.ndarray[tuple[" + ", ".join(
                    "int" if d in ("M", "N") else d
                    for d in _split_top_level(m.group("dims"))) + "]",
                line)
            count += n
        out_lines.append(line)
    return "".join(out_lines), count


_BARE_GENERIC_RE = re.compile(
    r"(?<![\w.])(?P<name>dict|list|tuple|set|typing\.Callable)(?![\w.\[])")
_BARE_GENERIC_ARGS = {
    "dict": "[typing.Any, typing.Any]",
    "list": "[typing.Any]",
    "tuple": "[typing.Any, ...]",
    "set": "[typing.Any]",
    "typing.Callable": "[..., typing.Any]",
}


def _parametrize_bare_generics(ann: str) -> tuple[str, int]:
    """``py::dict`` / ``py::tuple`` / ``py::function`` print as bare
    ``dict`` / ``tuple`` / ``Callable``. Spell out the implicit ``Any``
    arguments: same meaning, but ``mypy --strict`` users whose path
    reaches the stub as source (MYPYPATH, editable checkouts) stop
    seeing ``type-arg`` errors in it."""
    return _BARE_GENERIC_RE.subn(
        lambda m: m.group("name") + _BARE_GENERIC_ARGS[m.group("name")], ann)


def _fix_signatures(text: str) -> tuple[str, dict[str, list[str]]]:
    """Make every one-line ``def`` valid and mypy-clean.

    * Required-after-optional: pybind allows ``f(a=1, b)`` (it fills
      positionally) but Python does not. Insert ``*`` before the first
      such parameter, i.e. the trailing parameters become keyword-only
      in the stub -- the contract ``py::kw_only()`` will give them in
      the bindings (task 1.3). Every in-repo caller passes keywords.
    * Implicit Optional: ``cb: Callable[...] = None`` is an error under
      PEP 484 (mypy's default). Annotate it ``... | None``, which is
      what the binding accepts. Task 1.4 types these in the bindings.
    """
    fixed: dict[str, list[str]] = {"kw_only": [], "optional": [], "bare_generic": []}
    out_lines = []
    current_class = ""
    for line in text.splitlines(keepends=True):
        mcls = re.match(r"^class (\w+)", line)
        if mcls:
            current_class = mcls.group(1)
        elif re.match(r"^def ", line):
            current_class = ""
        m = _DEF_RE.match(line.rstrip("\n"))
        if not m:
            out_lines.append(line)
            continue
        fname = re.search(r"def (\w+)\(", m.group("head")).group(1)  # type: ignore[union-attr]
        qual = f"{current_class}.{fname}" if current_class and line.startswith("    ") else fname
        params = _split_top_level(m.group("params"))
        new_params: list[str] = []
        seen_default = False
        seen_star = False
        for p in params:
            name, ann, default = _split_param(p)
            if name.startswith("*") or name == "/":
                seen_star = seen_star or name.startswith("*")
                new_params.append(p)
                continue
            if default is None and seen_default and not seen_star:
                new_params.append("*")
                seen_star = True
                fixed["kw_only"].append(qual)
            if ann is not None:
                new_ann, n = _parametrize_bare_generics(ann)
                if n:
                    fixed["bare_generic"].append(f"{qual}({name})")
                    p = p.replace(ann, new_ann, 1)
                    ann = new_ann
            if default is not None:
                seen_default = True
                if default == "None" and ann is not None and not _accepts_none(ann):
                    p = f"{name}: {ann} | None = None"
                    fixed["optional"].append(f"{qual}({name})")
            new_params.append(p)
        tail, n = _parametrize_bare_generics(m.group("tail"))
        if n:
            fixed["bare_generic"].append(f"{qual}(->)")
        line = m.group("head") + ", ".join(new_params) + tail + "\n"
        out_lines.append(line)
    return "".join(out_lines), fixed


# ---------------------------------------------------------------------------
# Overlay merge
# ---------------------------------------------------------------------------
def _member_name(node: ast.stmt) -> str | None:
    if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
        return node.name
    if isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
        return node.target.id
    if isinstance(node, ast.Assign) and len(node.targets) == 1 \
            and isinstance(node.targets[0], ast.Name):
        return node.targets[0].id
    return None


def _node_span(node: ast.stmt) -> tuple[int, int]:
    """1-based inclusive line span, decorators included."""
    start = node.lineno
    for dec in getattr(node, "decorator_list", []):
        start = min(start, dec.lineno)
    end = node.end_lineno or node.lineno
    return start, end


def _docstring_node(fn: ast.stmt) -> ast.Expr | None:
    body = getattr(fn, "body", [])
    if body and isinstance(body[0], ast.Expr) \
            and isinstance(body[0].value, ast.Constant) \
            and isinstance(body[0].value.value, str):
        return body[0]
    return None


def merge_overlay(text: str, overlay_src: str) -> tuple[str, list[str]]:
    """Merge the overlay's class members and imports into ``text``.

    Members are copied as source text (not ``ast.unparse``) so the
    overlay's formatting survives. A one-line ``def ...: ...`` without a
    docstring gets the docstring of the generated member it replaces.
    """
    overlay = ast.parse(overlay_src)
    olines = overlay_src.splitlines(keepends=True)
    stub = ast.parse(text)
    lines = text.splitlines(keepends=True)
    stub_classes = {n.name: n for n in stub.body if isinstance(n, ast.ClassDef)}
    merged: list[str] = []
    edits: list[tuple[int, int, str]] = []  # (start, end, replacement); 1-based, end inclusive

    for ocls in (n for n in overlay.body if isinstance(n, ast.ClassDef)):
        scls = stub_classes.get(ocls.name)
        if scls is None:
            raise StubError(
                f"overlay class {ocls.name!r} is not in {MODULE}; "
                "remove it from scripts/stubs_overlay.pyi")
        names = {_member_name(n) for n in ocls.body} - {None}
        # Docstrings (as source text) of the generated members we replace.
        docs: dict[str, str] = {}
        for member in scls.body:
            name = _member_name(member)
            if name in names:
                doc = _docstring_node(member)
                if doc is not None and name not in docs:
                    docs[name] = ast.get_source_segment(text, doc) or ""  # type: ignore[index]
                s, e = _node_span(member)
                edits.append((s, e, ""))
        chunks: list[str] = []
        documented: set[str] = set()
        for member in ocls.body:
            name = _member_name(member)
            s, e = _node_span(member)
            # Attribute docstrings (a string right after ``x: T``) are
            # separate statements; they travel with the text as written.
            src = "".join(olines[s - 1:e])
            if (isinstance(member, ast.FunctionDef) and name in docs
                    and name not in documented and _docstring_node(member) is None):
                body = member.body
                if not (len(body) == 1 and isinstance(body[0], ast.Expr)
                        and body[0].value.lineno == member.end_lineno
                        and isinstance(body[0].value, ast.Constant)
                        and body[0].value.value is Ellipsis):
                    raise StubError(
                        f"overlay {ocls.name}.{name}: write it as a one-line "
                        "`def ...: ...` (or give it its own docstring)")
                last = olines[e - 1]
                head = last[:body[0].col_offset].rstrip()
                src = "".join(olines[s - 1:e - 1]) + head + "\n" \
                    + "        " + docs[name] + "\n        ...\n"
                documented.add(name)
            chunks.append(src)
            if name and f"{ocls.name}.{name}" not in merged:
                merged.append(f"{ocls.name}.{name}")
        insert_at = scls.end_lineno or scls.lineno
        edits.append((insert_at + 1, insert_at, OVERLAY_MARKER + "\n" + "".join(chunks)))

    # Apply bottom-up so earlier line numbers stay valid.
    for start, end, repl in sorted(edits, key=lambda e: (e[0], e[1]), reverse=True):
        lines[start - 1:end] = [repl] if repl else []
    out = "".join(lines)

    # Top-level imports the overlay needs.
    import_lines = [ast.unparse(n) for n in overlay.body
                    if isinstance(n, (ast.Import, ast.ImportFrom))]
    missing = [ln for ln in import_lines
               if not re.search(rf"(?m)^{re.escape(ln)}$", out)]
    if missing:
        last_import = max(m.end() for m in re.finditer(r"(?m)^(?:import|from) .*$", out))
        out = out[:last_import] + "\n" + "\n".join(missing) + out[last_import:]
    return out, merged


# ---------------------------------------------------------------------------
# Validation
# ---------------------------------------------------------------------------
def code_without_docstrings(text: str) -> str:
    """The stub's code tokens, with every string literal removed."""
    toks = tokenize.generate_tokens(io.StringIO(text).readline)
    return " ".join(t.string for t in toks
                    if t.type not in (tokenize.STRING, tokenize.COMMENT))


def validate(text: str) -> None:
    try:
        ast.parse(text)
    except SyntaxError as exc:
        raise StubError(f"generated stub is not valid Python: {exc}") from exc
    code = code_without_docstrings(text)
    problems = []
    if "pybind11_stubgen" in code:
        problems.append("imports pybind11_stubgen")
    if re.search(r"0x[0-9a-fA-F]{6,}", code):
        problems.append("contains an object address (0x...)")
    if "::" in code:
        problems.append("contains a C++ qualified name (::)")
    if problems:
        raise StubError("generated stub " + "; ".join(problems))


# ---------------------------------------------------------------------------
# Driver
# ---------------------------------------------------------------------------
def build_stub(pythonpath: list[str], verbose: bool = True) -> str:
    raw = run_stubgen(pythonpath)
    text, n_fixed = _strip_fixed_size(raw)
    text, n_repr = _rewrite_object_reprs(text)
    text, n_cpp = _rewrite_cpp_names(text)
    text, sig_fixes = _fix_signatures(text)
    text, n_eq = _fix_eq_ne(text)
    text, n_tv = _bind_attribute_typevars(text)
    text, merged = merge_overlay(text, OVERLAY_PATH.read_text(encoding="utf-8"))
    text = HEADER.format(version=STUBGEN_VERSION) + text
    # stubgen indents the blank lines inside docstrings; strip that
    # whitespace so the stub passes the repo's ruff W rules unmodified.
    text = re.sub(r"(?m)^[ \t]+$", "", text)
    if not text.endswith("\n"):
        text += "\n"
    validate(text)
    if verbose:
        log = sys.stderr.write
        log(f"stub: {text.count(chr(10))} lines, "
            f"{len(re.findall(r'(?m)^ *def ', text))} defs\n")
        log(f"  FixedSize annotations -> list: {n_fixed}\n")
        log(f"  object-repr defaults -> ...: {n_repr}\n")
        log(f"  C++ type names -> Python class: {n_cpp}\n")
        log(f"  keyword-only inserted: {', '.join(sig_fixes['kw_only']) or '-'}\n")
        log(f"  implicit Optional fixed: {len(sig_fixes['optional'])}\n")
        log(f"  bare dict/list/tuple/Callable parametrized: "
            f"{', '.join(sig_fixes['bare_generic']) or '-'}\n")
        log(f"  __eq__/__ne__ operand -> object: {n_eq}\n")
        log(f"  attribute shape TypeVars -> int: {n_tv}\n")
        log(f"  overlay members: {', '.join(merged)}\n")
    return text


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true",
                    help="regenerate into memory and exit 1 with a diff "
                         "if the committed stub differs")
    ap.add_argument("--pythonpath", action="append", default=None,
                    metavar="DIR",
                    help="directory to prepend to PYTHONPATH so the built "
                         "pulsim is imported (repeatable; default: the "
                         "repo's python/ or build/python/ if it holds the "
                         "extension, else the installed pulsim)")
    ap.add_argument("-q", "--quiet", action="store_true")
    args = ap.parse_args(argv)
    pythonpath = args.pythonpath if args.pythonpath is not None else _default_pythonpath()
    try:
        text = build_stub(pythonpath, verbose=not args.quiet)
    except StubError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2
    if args.check:
        current = STUB_PATH.read_text(encoding="utf-8") if STUB_PATH.exists() else ""
        if current == text:
            print(f"{STUB_PATH.relative_to(ROOT)} is up to date")
            return 0
        rel = str(STUB_PATH.relative_to(ROOT))
        sys.stdout.writelines(difflib.unified_diff(
            current.splitlines(keepends=True), text.splitlines(keepends=True),
            fromfile=f"{rel} (committed)", tofile=f"{rel} (regenerated)"))
        print(f"\n{rel} is stale: run python scripts/generate_stubs.py",
              file=sys.stderr)
        return 1
    STUB_PATH.write_text(text, encoding="utf-8")
    print(f"wrote {STUB_PATH.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

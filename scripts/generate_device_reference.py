#!/usr/bin/env python3
"""Generate docs/device-reference.md from the device field tables.

add-unified-device-interface group 12. Every row comes from
``pulsim._pulsim.device_field_table()`` (the C++ ``ir::kKindFields``, the
same rows the builder validates, ``components()`` lists and the YAML
registry reads), plus the builder method's signature for its defaults.

    python scripts/generate_device_reference.py           # rewrite the page
    python scripts/generate_device_reference.py --check   # exit 1 if stale

Run it against the built extension (``PYTHONPATH=python``).
"""

from __future__ import annotations

import argparse
import difflib
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PAGE = ROOT / "docs" / "device-reference.md"

HEADER = """# Device reference

<!-- GENERATED by scripts/generate_device_reference.py from the device
     field tables (core/include/pulsim/ir/fields.hpp). Do not edit by hand:
     edit the table and rerun the script (--check reports a stale page;
     python/tests/test_device_fields.py fails on one). -->

One section per device kind. **Key** is the builder argument and the
`components()` params key; the YAML registry entry (`type: <kind>` with
`pins:`) and `with_value("<device>.<name>")` use **Name**. **Bound** is
checked by `with_value` (not on a branch-form switch's own values),
`bind_param` / `set_param` and the YAML registry reader (a derived field
such as R is checked as the field it is stored as, G), each naming the
device and the field; the `add_*` methods keep
their own checks (some accept more: a negative resistor, `m = 0`, an
ideal switch's `g_off = 0`). **Default** is the model's default
(the value-initialised parameter set; "-" where that value is outside
the bound, i.e. there is no usable default). **Builder** is the `add_*`
method's own handling: `required`, `same` (its default equals the
model's), its own default when it differs, `not an argument`, or `?`
(no readable signature: a Python wrapper). A field marked
*derived* is stored as another field (R as G = 1/R); one marked
*in components()* is listed in `CircuitBuilder.components()` params (the
scalars it always listed); `Circuit.devices()` lists every field.
"""


def _builder_args(method) -> dict[str, str | None] | None:
    """name -> default text (None: required), from the signature line
    pybind11 writes; None when the method has no readable signature."""
    doc = (getattr(method, "__doc__", None) or "").split("\n", 1)[0]
    if "(*args, **kwargs)" in doc or "(" not in doc:
        return None
    out: dict[str, str | None] = {}
    for m in re.finditer(r"(\w+): [^,=()]+(?:\[[^\]]*\])?(?: = ([^,()]+))?(?=[,)])", doc):
        out[m.group(1)] = m.group(2).strip() if m.group(2) else None
    return out


def _num(x: float) -> str:
    return repr(float(x)) if x == x else "nan"


def _within(bound: str, x: float) -> bool:
    """ir::within for the bound texts ir::bound_text writes."""
    import math
    if not math.isfinite(x):
        return False
    return {"a finite number": True, "a finite number > 0": x > 0,
            "a finite number >= 0": x >= 0, "a number in [0, 1]": 0 <= x <= 1}[bound]


def _same(text: str, x: float) -> bool:
    try:
        return float(text) == float(x)
    except ValueError:
        return False


def render() -> str:
    from pulsim import _pulsim as k
    out = [HEADER]
    for row in k.device_field_table():
        kind = row["kind"]
        out.append(f"\n## `{kind}`\n")
        meth = getattr(k.CircuitBuilder, f"add_{kind}", None)
        out.append(f"Builder: `CircuitBuilder.add_{kind}`." if meth else
                   "Builder: no `add_" + kind + "` method (built by another one).")
        if not row["fields"]:
            out.append("\nNo scalar value fields (its parameters are a table or its "
                       "model's own field list).\n")
            continue
        args = _builder_args(meth) if meth else None
        out.append("\n| Name | Key | Unit | Bound | Default | Builder | Description |")
        out.append("|---|---|---|---|---|---|---|")
        for f in row["fields"]:
            flags = [w for w, on in (("derived", f["derived"]),
                                     ("in components()", f["listed"])) if on]
            desc = f["description"] + (f" (*{', '.join(flags)}*)" if flags else "")
            if args is None:
                bshow = "?"                      # no readable signature
            elif f["key"] not in args:
                bshow = "not an argument"
            elif args[f["key"]] is None:
                bshow = "required"
            else:
                b = args[f["key"]]
                bshow = "same" if _same(b, f["default"]) else f"`{b}`"
            key = f["key"] if f["key"] != f["name"] else ""
            dflt = f"`{_num(f['default'])}`" if _within(f["bound"], f["default"]) else "-"
            out.append(f"| `{f['name']}` | {('`' + key + '`') if key else ''} | {f['unit']} | "
                       f"{f['bound']} | {dflt} | {bshow} | {desc} |")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    ap.add_argument("--check", action="store_true", help="fail if the page is stale")
    a = ap.parse_args()
    text = render()
    if a.check:
        old = PAGE.read_text(encoding="utf-8") if PAGE.exists() else ""
        if old != text:
            sys.stdout.writelines(difflib.unified_diff(
                old.splitlines(True), text.splitlines(True), str(PAGE), "generated", n=1))
            print(f"\n{PAGE.relative_to(ROOT)} is stale: run "
                  "python scripts/generate_device_reference.py", file=sys.stderr)
            return 1
        print(f"{PAGE.relative_to(ROOT)} is up to date")
        return 0
    PAGE.write_text(text, encoding="utf-8")
    print(f"wrote {PAGE.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
